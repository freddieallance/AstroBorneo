import assert from 'node:assert/strict';
import { normalize } from './providers';
import { validateDates, weather } from './service';
// TEST FIXTURE — NOT REAL NASA DATA. Never bundled as an observation.
const fixture = [{ flrID: '2001-01-01T00:00:00-FLR-TEST', beginTime: '2001-01-01T00:00Z', link: 'https://ccmc.gsfc.nasa.gov/DONKI/view/FLR/test/-1' }];
assert.equal(validateDates('2024-02-30', '2024-03-01'), false);
assert.equal(validateDates('2024-01-01', '2024-02-10'), false);
assert.equal(validateDates('2024-05-10', '2024-05-10'), true);
assert.equal(normalize(fixture, 'NASA_CCMC', 'FLR', '2001-01-02T00:00:00Z').records.length, 1);
assert.equal(normalize([{ ...fixture[0], beginTime: undefined }], 'NASA_CCMC', 'FLR', '').incomplete, 1);
assert.equal(normalize([{ ...fixture[0], link: 'https://evil.example/' }], 'NASA_CCMC', 'FLR', '').records.length, 0);
const originalFetch = globalThis.fetch;
const response = (body: unknown, status = 200) => async () => new Response(JSON.stringify(body), { status });
const sleep = () => new Promise(r => setTimeout(r, 2050));
process.env.NASA_DONKI_PROVIDER = 'NASA_OPEN_APIS';
delete process.env.NASA_API_KEY;
assert.equal((await weather('FLR', '2001-01-01', '2001-01-01', 'auto')).status, 'NOT_CONFIGURED');
process.env.NASA_DONKI_PROVIDER = 'NASA_CCMC';
globalThis.fetch = response([]);
await sleep();
const empty = await weather('FLR', '2001-01-02', '2001-01-02', 'auto');
assert.equal(empty.status, 'EMPTY'); assert.equal(empty.records.length, 0);
globalThis.fetch = response(fixture);
await sleep();
const good = await weather('FLR', '2001-01-03', '2001-01-03', 'auto');
assert.equal(good.mode, 'LIVE_DATA');
const cached = await weather('FLR', '2001-01-03', '2001-01-03', 'auto');
assert.equal(cached.cached, true); assert.equal(cached.records[0].fetchedAtUTC, good.records[0].fetchedAtUTC);
globalThis.fetch = response({}, 429); await sleep();
assert.equal((await weather('FLR', '2001-01-04', '2001-01-04', 'auto')).status, 'RATE_LIMITED');
globalThis.fetch = async () => { throw new Error('SECRET_SENTINEL_DO_NOT_RETURN'); }; await sleep();
const failed = await weather('FLR', '2001-01-05', '2001-01-05', 'auto');
assert.equal(failed.mode, 'ARCHIVED_DATA');
assert.ok(!JSON.stringify(failed).includes('SECRET_SENTINEL'));
assert.equal((await weather('FLR', '', '', 'archived')).mode, 'ARCHIVED_DATA');
assert.equal((await weather('FLR', '', '', 'simulated')).records.length, 0);
globalThis.fetch = originalFetch;
console.log('PASS: missing key, empty, failure, rate limit, safe errors, archive, simulated, normalization, invalid dates and cache timestamps.');
